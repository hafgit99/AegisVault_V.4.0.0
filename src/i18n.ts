const mojibakePattern = /(?:\u00C2.|\u00C3.|\u00C4.|\u00C5.)/;

const repairMojibakeString = (value: string): string => {
  if (!mojibakePattern.test(value)) return value;

  try {
    const bytes = Uint8Array.from(Array.from(value, (char) => char.charCodeAt(0) & 0xff));
    const decoded = new TextDecoder('utf-8', { fatal: false }).decode(bytes);

    if (!decoded || decoded.includes('\uFFFD')) return value;

    const decodedLooksBetter =
      (decoded.match(/[çğıİöşüÇĞİÖŞÜ]/g)?.length ?? 0) >=
      (value.match(/[çğıİöşüÇĞİÖŞÜ]/g)?.length ?? 0);

    return decodedLooksBetter ? decoded : value;
  } catch {
    return value;
  }
};

const repairTranslationTree = <T,>(node: T): T => {
  if (typeof node === 'string') {
    return repairMojibakeString(node) as T;
  }

  if (Array.isArray(node)) {
    return node.map((item) => repairTranslationTree(item)) as T;
  }

  if (node && typeof node === 'object') {
    const repairedEntries = Object.entries(node as Record<string, unknown>).map(([key, value]) => [
      key,
      repairTranslationTree(value),
    ]);
    return Object.fromEntries(repairedEntries) as T;
  }

  return node;
};

